/** 宿主返回的稳定超时标记（见 host 侧 E_TIMEOUT 前缀）。 */
const TIMEOUT_TOKEN = 'E_TIMEOUT'

/**
 * 把宿主的错误对象翻译成当前语言；收录不到的 code 回退到宿主原文。
 * 同时兼容宿主历史上的中文/英文超时文案，避免旧构建下丢失提示。
 */
export function tError(code: string | undefined, fallback: string): string {
  if (code !== undefined && HOST_ERRORS[code] !== undefined) return HOST_ERRORS[code][lang]
  if (fallback.includes(TIMEOUT_TOKEN) || fallback.includes('超时') || fallback.includes('timed out')) {
    return HOST_ERRORS.timeout[lang]
  }
  return fallback
}

export function t(key: string, params?: Record<string, string>): string {
  const text = DICTS[lang][key] ?? DICTS.zh[key] ?? key
  if (params === undefined) return text
  return text.replace(/\{(\w+)\}/g, (match, name: string) => params[name] ?? match)
}

/**
 * React hook：当活动语言变化时重新渲染组件。返回的 t() 是模块级稳定引用，
 * 因此被 memo 化的回调可以安全地依赖它。
 */
export function useT(): (key: string, params?: Record<string, string>) => string {
  useSyncExternalStore(subscribe, getSnapshot)
  return t
}
